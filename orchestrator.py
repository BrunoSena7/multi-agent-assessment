"""Sequential multi-agent assessment pipeline adapted from the course project.

The original exercise used CrewAI agents/tasks. This standalone edition keeps
its three-role sequential design while making the hand-off explicit and testable.
"""
from __future__ import annotations

import json
from typing import Any, Callable, Optional

from agents import (
    REVIEWER_SYSTEM,
    STUDENT_SYSTEM,
    TEACHER_SYSTEM,
    reviewer_input,
    student_input,
    teacher_input,
)


class MultiAgentAssessment:
    def __init__(self, api_key: Optional[str] = None, model: str = "gpt-4o-mini", client=None):
        self.model = model
        self.client = client
        if self.client is None:
            if not api_key:
                raise ValueError("Configure OPENAI_API_KEY para executar os agentes com LLM.")
            try:
                from openai import OpenAI
            except ImportError as exc:
                raise RuntimeError("Instale as dependências com: pip install -r requirements.txt") from exc
            self.client = OpenAI(api_key=api_key)

    def _run_agent(self, role: str, system_prompt: str, user_prompt: str) -> dict[str, Any]:
        response = self.client.chat.completions.create(
            model=self.model,
            temperature=0.2,
            response_format={"type": "json_object"},
            messages=[
                {"role": "system", "content": system_prompt},
                {"role": "user", "content": user_prompt},
            ],
        )
        content = response.choices[0].message.content
        if not content:
            raise RuntimeError(f"O agente {role} retornou uma resposta vazia.")
        try:
            return json.loads(content)
        except json.JSONDecodeError as exc:
            raise RuntimeError(f"O agente {role} não retornou JSON válido.") from exc

    def run(
        self, discipline: str, topic: str, difficulty: str = "Intermediária",
        question_count: int = 5, on_step: Optional[Callable[[str], None]] = None,
    ) -> dict[str, Any]:
        if not discipline.strip() or not topic.strip():
            raise ValueError("Disciplina e tópico são obrigatórios.")
        if not 1 <= question_count <= 8:
            raise ValueError("A quantidade de questões deve ficar entre 1 e 8.")

        # Agent 1 — Teacher: generates the assessment and answer key.
        if on_step:
            on_step("Agente 1/3 — Professor: criando a prova e o gabarito.")
        exam = self._run_agent(
            "Professor", TEACHER_SYSTEM,
            teacher_input(discipline.strip(), topic.strip(), difficulty, question_count),
        )
        questions = exam.get("questions")
        if not isinstance(questions, list) or len(questions) != question_count:
            raise RuntimeError("O agente Professor não gerou a quantidade esperada de questões.")
        for index, question in enumerate(questions, start=1):
            question.setdefault("id", index)
            question.setdefault("type", "open")
            question.setdefault("options", {})
            question.setdefault("points", 2)
            if not question.get("question") or "correct_answer" not in question:
                raise RuntimeError(f"Questão {index} veio sem enunciado ou gabarito.")

        # Agent 2 — Student: receives only the questions, never the answer key.
        if on_step:
            on_step("Agente 2/3 — Estudante: respondendo sem acesso ao gabarito.")
        student = self._run_agent("Aluno", STUDENT_SYSTEM, student_input(questions))
        answers = student.get("answers")
        if not isinstance(answers, list):
            raise RuntimeError("O agente Aluno não retornou a lista de respostas.")

        # Agent 3 — Reviewer: receives the teacher key and the student's answers.
        if on_step:
            on_step("Agente 3/3 — Revisor: avaliando respostas e feedback.")
        review = self._run_agent(
            "Revisor", REVIEWER_SYSTEM, reviewer_input(questions, answers)
        )
        if not isinstance(review.get("corrections"), list):
            raise RuntimeError("O agente Revisor não retornou a lista de correções.")

        max_score = sum(float(q.get("points", 2)) for q in questions)
        # Recompute the final score from validated per-question values rather than
        # trusting a free-form aggregate generated by the reviewer LLM.
        question_points = {str(q["id"]): float(q.get("points", 2)) for q in questions}
        validated_total = 0.0
        seen_corrections: set[str] = set()
        for correction in review["corrections"]:
            question_id = str(correction.get("id"))
            if question_id not in question_points or question_id in seen_corrections:
                continue
            seen_corrections.add(question_id)
            maximum = question_points[question_id]
            try:
                awarded = float(correction.get("awarded_points", 0))
            except (TypeError, ValueError):
                awarded = 0.0
            awarded = max(0.0, min(awarded, maximum))
            correction["awarded_points"] = awarded
            correction["max_points"] = maximum
            validated_total += awarded
        review["max_score"] = max_score
        review["score"] = min(validated_total, max_score)
        return {
            "discipline": discipline.strip(),
            "topic": topic.strip(),
            "difficulty": difficulty,
            "exam": exam,
            "student": student,
            "review": review,
            "model": self.model,
        }


def to_markdown(result: dict[str, Any]) -> str:
    lines = [
        f"# Relatório de avaliação — {result['discipline']}",
        f"**Tópico:** {result['topic']}  \n**Dificuldade:** {result['difficulty']}  \n**Modelo:** {result['model']}",
        "\n## Prova e gabarito",
    ]
    for question in result["exam"]["questions"]:
        lines.append(f"### Questão {question['id']}\n{question['question']}")
        for key, value in question.get("options", {}).items():
            lines.append(f"- {key}) {value}")
        lines.append(f"**Gabarito:** {question['correct_answer']}")
        lines.append(f"**Explicação:** {question.get('explanation', 'Não fornecida.')}")
    lines.extend([
        "\n## Respostas do estudante",
        str(result["student"].get("answers", [])),
        "\n## Correção",
        f"**Nota:** {result['review']['score']} / {result['review']['max_score']}",
    ])
    for correction in result["review"]["corrections"]:
        lines.append(
            f"- **Questão {correction.get('id')}:** "
            f"{correction.get('awarded_points', 0)}/{correction.get('max_points', 0)} — "
            f"{correction.get('feedback', '')}"
        )
    lines.append(f"\n**Feedback geral:** {result['review'].get('overall_feedback', '')}")
    return "\n\n".join(lines)
